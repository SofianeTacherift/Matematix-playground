#include "matpx_object_operations.h"

#define DEFINE_BINARY_OPERATOR_FUNCTION_SAME_TYPE(OPERATOR_NAME, OPERATOR, TYPE_NAME, ATTRIBUTE_NAME, TYPE_NUM) \
    \
    MatxObject * TYPE_NAME##_##OPERATOR_NAME##_##TYPE_NAME( MatxObject *o1, MatxObject *o2) {\
        MatxObject *res = MatxObject_new();\
        res->ATTRIBUTE_NAME=o1->ATTRIBUTE_NAME OPERATOR o2->ATTRIBUTE_NAME;\
        res->type=TYPE_NUM;\
        return res;\
    }\

#define DEFINE_BINARY_OPERATOR_FUNCTION(OPERATOR_NAME,  OPERATOR, TYPE1_NAME, TYPE2_NAME, ATTRIBUTE1, ATTRIBUTE2, TYPE1_NUM, TYPE1_C_TYPE) \
    \
    MatxObject * TYPE1_NAME##_##OPERATOR_NAME##_##TYPE2_NAME( MatxObject *o1, MatxObject *o2) {\
        MatxObject *res = MatxObject_new();\
        res->ATTRIBUTE1=o1->ATTRIBUTE1 OPERATOR (TYPE1_C_TYPE)o2->ATTRIBUTE2;\
        res->type=TYPE1_NUM;\
        return res;\
    }
#define DEFINE_BINARY_OPERATOR_FUNCTION_WEAK(OPERATOR_NAME, OPERATOR, TYPE1_NAME, TYPE2_NAME, ATTRIBUTE1, ATTRIBUTE2,  TYPE2_NUM, TYPE2_C_TYPE) \
    MatxObject * TYPE1_NAME##_##OPERATOR_NAME##_##TYPE2_NAME( MatxObject *o1, MatxObject *o2) {\
    MatxObject *res = MatxObject_new();\
    res->ATTRIBUTE2= (TYPE2_C_TYPE) o1->ATTRIBUTE1 OPERATOR o2->ATTRIBUTE2;\
    res->type=TYPE2_NUM;\
    return res;\
    }
#define DEF_BINARY_OPERATOR_COMBINAISON_FUNCTION(OPERATOR_NAME,  OPERATOR, TYPE1_NAME, TYPE2_NAME,ATTRIBUTE1, ATTRIBUTE2, TYPE1_NUM, TYPE2_NUM, TYPE1_C_TYPE, TYPE2_C_TYPE) \
    \
    DEFINE_BINARY_OPERATOR_FUNCTION(OPERATOR_NAME, TYPE1_NAME, TYPE2_NAME, ATTRIBUTE1, ATTRIBUTE2, OPERATOR, TYPE1_NUM, TYPE1_C_TYPE)\
    DEFINE_BINARY_OPERATOR_FUNCTION(OPERATOR_NAME, TYPE2_NAME, TYPE1_NAME, ATTRIBUTE2, ATTRIBUTE1, OPERATOR, TYPE2_NUM, TYPE2_C_TYPE)

#define DEF_BINARY_OPERATOR_COMBINAISON_FUNCTION_WEAK(OPERATOR_NAME,  OPERATOR, TYPE1_NAME, TYPE2_NAME,ATTRIBUTE1, ATTRIBUTE2, TYPE2_NUM, TYPE2_C_TYPE) \
    \
    DEFINE_BINARY_OPERATOR_FUNCTION_WEAK(OPERATOR_NAME, OPERATOR, TYPE1_NAME, TYPE2_NAME, ATTRIBUTE1, ATTRIBUTE2, TYPE2_NUM , TYPE2_C_TYPE)\
    DEFINE_BINARY_OPERATOR_FUNCTION(OPERATOR_NAME, OPERATOR, TYPE2_NAME, TYPE1_NAME, ATTRIBUTE2, ATTRIBUTE1, TYPE2_NUM, TYPE2_C_TYPE)

